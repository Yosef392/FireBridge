"use client";

import { useMemo, useState } from "react";
import { ArrowDownRight, ArrowUpRight, BrainCircuit, CircleDashed, FlaskConical, Target } from "lucide-react";
import { Card, CardContent } from "@/components/ui/card";
import { Segmented } from "@/components/ui/segmented";
import { ChartCard, ChartSkeleton, DemoBadge, ErrorState, Notice, PageHeader, RiskBadge } from "@/components/dashboard/primitives";
import { FeatureImportanceChart } from "@/components/charts/charts";
import { PredictionMap } from "@/components/map";
import { usePredictions } from "@/hooks/use-fire-data";
import { useFilters } from "@/context/filters";
import { REGION_BY_ID } from "@/data/demo/regions";
import { RISK_COLORS } from "@/lib/colors";
import { RISK_LEVELS, type ForecastHorizon, type ModelMetrics } from "@/lib/types";
import { cn, fmtPct, fmtSignedPct } from "@/lib/utils";

const HORIZONS: { value: ForecastHorizon; label: string }[] = [
  { value: "7d", label: "Next 7 days" },
  { value: "14d", label: "Next 14 days" },
  { value: "30d", label: "Next 30 days" },
];

const METRICS: { key: keyof ModelMetrics; label: string; help: string }[] = [
  { key: "precision", label: "Precision", help: "Of the areas flagged as elevated, how many truly were" },
  { key: "recall", label: "Recall", help: "Of the truly elevated areas, how many were flagged" },
  { key: "f1", label: "F1-score", help: "Harmonic mean of precision and recall" },
  { key: "rocAuc", label: "ROC-AUC", help: "Ranking quality across all decision thresholds" },
];

export default function PredictionsPage() {
  const { status, data, error, retry } = usePredictions();
  const { filters, setFilter } = useFilters();
  const [horizon, setHorizon] = useState<ForecastHorizon>("7d");

  const rows = useMemo(() => {
    if (!data) return [];
    return data.predictions
      .filter((p) => p.horizon === horizon)
      .sort((a, b) => b.probability - a.probability);
  }, [data, horizon]);

  const dist = useMemo(() => RISK_LEVELS.map((r) => ({ risk: r, n: rows.filter((p) => p.risk === r).length })), [rows]);
  const simulated = !data || data.model.status === "simulated";

  return (
    <div className="space-y-6">
      <PageHeader
        eyebrow="Predictions"
        title="Elevated fire activity outlook"
        description="Region-level probability that fire activity will exceed its seasonal norm over the forecast horizon. This page shows the prediction interface with sample outputs until the trained model is connected."
        actions={
          <Segmented ariaLabel="Forecast horizon" value={horizon} onChange={setHorizon} options={HORIZONS} />
        }
      />

      {/* Simulated vs real banner — intentionally prominent */}
      <div
        className={cn(
          "flex flex-col gap-3 rounded-2xl border p-4 md:flex-row md:items-center md:justify-between",
          simulated ? "border-fire-soft/35 bg-[repeating-linear-gradient(135deg,rgba(255,179,71,0.06)_0_10px,transparent_10px_20px)]" : "border-success/35 bg-success/5",
        )}
      >
        <div className="flex items-start gap-3">
          <span className={cn("mt-0.5 flex size-9 shrink-0 items-center justify-center rounded-xl", simulated ? "bg-fire-soft/15 text-fire-soft" : "bg-success/15 text-success")}>
            {simulated ? <FlaskConical className="size-5" /> : <BrainCircuit className="size-5" />}
          </span>
          <div>
            <p className="text-sm font-semibold">
              {simulated ? "SIMULATED PREDICTIONS — sample outputs, not model results" : "Live model outputs"}
            </p>
            <p className="mt-0.5 text-xs leading-relaxed text-muted">
              {simulated
                ? "Every probability, risk category and expected range on this page is hand-authored to demonstrate the interface. No trained model has produced these values and they must not be used for decisions."
                : `Generated by ${data?.model.name} v${data?.model.version}.`}
            </p>
          </div>
        </div>
        <div className="flex shrink-0 flex-wrap gap-2 text-[11px]">
          <span className="rounded-md border border-border bg-surface/70 px-2 py-1 text-muted">
            Model: <span className="text-foreground">{data?.model.name ?? "—"}</span>
          </span>
          <span className="rounded-md border border-border bg-surface/70 px-2 py-1 font-mono text-muted">v{data?.model.version ?? "—"}</span>
          <span className={cn("rounded-md border px-2 py-1 font-medium", simulated ? "border-fire-soft/40 text-fire-soft" : "border-success/40 text-success")}>
            {simulated ? "status: simulated" : "status: trained"}
          </span>
        </div>
      </div>

      {status === "error" && !data ? (
        <ErrorState error={error!} onRetry={retry} height={360} />
      ) : (
        <>
          {/* Distribution tiles */}
          <section aria-label="Risk category counts" className="grid grid-cols-2 gap-4 lg:grid-cols-4">
            {dist.map((d) => (
              <Card key={d.risk} className="overflow-hidden">
                <div className="absolute inset-x-0 top-0 h-0.5" style={{ background: RISK_COLORS[d.risk] }} />
                <CardContent className="p-4">
                  <RiskBadge risk={d.risk} />
                  <p className="mt-2 font-display text-2xl font-semibold tabular-nums">
                    {data ? d.n : "—"}
                    <span className="ml-1.5 text-xs font-normal text-muted">region{d.n === 1 ? "" : "s"}</span>
                  </p>
                  <p className="mt-0.5 text-[11px] text-subtle">
                    {d.risk === "Low" ? "P < 25%" : d.risk === "Moderate" ? "25% ≤ P < 50%" : d.risk === "High" ? "50% ≤ P < 75%" : "P ≥ 75%"}
                  </p>
                </CardContent>
              </Card>
            ))}
          </section>

          <div className="grid grid-cols-1 gap-6 xl:grid-cols-5">
            <ChartCard
              className="xl:col-span-3"
              title="Predicted activity by area"
              description={`${HORIZONS.find((h) => h.value === horizon)?.label} · circle size ∝ probability. Click a circle for details.`}
            >
              {data ? <PredictionMap predictions={rows} height={420} /> : <ChartSkeleton height={420} />}
            </ChartCard>

            <ChartCard className="xl:col-span-2" title="Regional risk ranking" description="Probability of elevated fire activity in the horizon">
              {!data ? (
                <ChartSkeleton height={420} />
              ) : (
                <ul className="space-y-2.5">
                  {rows.map((p) => {
                    const r = REGION_BY_ID[p.regionId];
                    const selected = filters.regionId === p.regionId;
                    return (
                      <li key={p.regionId}>
                        <button
                          type="button"
                          onClick={() => setFilter("regionId", selected ? "ALL" : p.regionId)}
                          className={cn(
                            "w-full cursor-pointer rounded-xl border p-3 text-left transition-colors",
                            selected ? "border-primary/50 bg-primary/5" : "border-border bg-surface/50 hover:border-border-strong",
                          )}
                          aria-pressed={selected}
                        >
                          <div className="flex items-center justify-between gap-2">
                            <span className="min-w-0">
                              <span className="block truncate text-sm font-medium">{r?.name}</span>
                              <span className="text-[11px] text-subtle">{r?.country}</span>
                            </span>
                            <RiskBadge risk={p.risk} />
                          </div>
                          <div className="mt-2.5 flex items-center gap-3">
                            <div className="h-1.5 flex-1 overflow-hidden rounded-full bg-surface-3">
                              <div className="h-full rounded-full" style={{ width: `${p.probability * 100}%`, background: RISK_COLORS[p.risk] }} />
                            </div>
                            <span className="w-10 text-right font-mono text-xs tabular-nums">{fmtPct(p.probability)}</span>
                          </div>
                          <div className="mt-2 flex flex-wrap items-center justify-between gap-2 text-[11px] text-muted">
                            <span>
                              Expected <span className="font-mono text-foreground">{p.expectedLow}–{p.expectedHigh}</span> detections
                            </span>
                            <span className={cn("inline-flex items-center gap-0.5 font-mono", p.changeVsBaseline > 0 ? "text-[#ff8f92]" : "text-[#5fd3b2]")}>
                              {p.changeVsBaseline > 0 ? <ArrowUpRight className="size-3" /> : <ArrowDownRight className="size-3" />}
                              {fmtSignedPct(p.changeVsBaseline)} vs baseline
                            </span>
                          </div>
                        </button>
                      </li>
                    );
                  })}
                </ul>
              )}
            </ChartCard>
          </div>

          <div className="grid grid-cols-1 gap-6 xl:grid-cols-5">
            <ChartCard
              className="xl:col-span-3"
              title="Feature importance"
              description="Relative contribution of each input feature (sample values illustrating the planned feature set)"
            >
              {data ? <FeatureImportanceChart data={data.featureImportance} /> : <ChartSkeleton height={340} />}
            </ChartCard>

            <ChartCard className="xl:col-span-2" title="Model evaluation" description="Held-out temporal test set (most recent season)" demo={false}>
              <div className="grid grid-cols-2 gap-3">
                {METRICS.map((m) => {
                  const v = data?.model.metrics[m.key] ?? null;
                  return (
                    <div key={m.key} className="rounded-xl border border-dashed border-border-strong bg-surface/40 p-3.5">
                      <p className="flex items-center gap-1.5 text-[11px] font-medium text-muted">
                        <Target className="size-3" aria-hidden /> {m.label}
                      </p>
                      <p className="mt-1.5 font-display text-2xl font-semibold tabular-nums">{v == null ? "—" : v.toFixed(3)}</p>
                      <p className="mt-1 text-[10.5px] leading-snug text-subtle">{m.help}</p>
                    </div>
                  );
                })}
              </div>
              <div className="mt-4 flex items-start gap-2.5 rounded-xl border border-border bg-surface/50 p-3 text-xs text-muted">
                <CircleDashed className="mt-0.5 size-4 shrink-0 text-subtle" aria-hidden />
                <p className="leading-relaxed">
                  <span className="font-medium text-foreground">Awaiting trained model.</span> Metrics are intentionally left
                  blank until the team’s model is evaluated. They will populate automatically from the{" "}
                  <code className="rounded bg-surface-3 px-1 font-mono text-[11px]">/api/v1/predictions</code> response.
                </p>
              </div>
              <div className="mt-3">
                <Notice tone="info">
                  Planned protocol: train on 2020–2023, validate and test on 2024 with a strict time split (no leakage),
                  report metrics per region and overall, and calibrate probabilities before assigning risk categories.
                </Notice>
              </div>
            </ChartCard>
          </div>

          <div className="flex flex-wrap items-center gap-2 text-[11px] text-subtle">
            <DemoBadge label="Simulated" /> Prediction target: <span className="text-muted">{data?.model.target ?? "—"}</span>
          </div>
        </>
      )}
    </div>
  );
}
